    function getCurrentPhoneme() {
        const filename = decodeURIComponent(window.location.pathname.split('/').pop() || '');
        return filename.replace(/\.html$/i, '').toLowerCase();
    }

    function escapeAttribute(value) {
        return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
    }

    function applyCuratedContent() {
        if (typeof sections === 'undefined' || typeof render !== 'function') return;
        const phoneme = getCurrentPhoneme();
        const curatedItems = curatedPhonemes[phoneme];
        if (!curatedItems) return;

        sections.danzi.items = curatedItems.map(function (item) {
            return { word: item[0], pinyin: item[1], emoji: item[2] };
        });
        sections.san.items = curatedThreeSyllables[phoneme].map(function (item) {
            return { word: item[0], pinyin: item[1], emoji: item[2] };
        });
        const twoSyllableItems = new Map(sections.shuang.items.map(function (item) {
            return [item.word, item];
        }));
        sections.shuang.items = curatedTwoSyllableWords[phoneme].map(function (word) {
            return twoSyllableItems.get(word);
        }).filter(Boolean);
        const sentenceItems = new Map(sections.duanju.items.map(function (item) {
            return [item.word, item];
        }));
        sections.duanju.items = curatedSentenceWords[phoneme].map(function (word) {
            return sentenceItems.get(word);
        }).filter(Boolean);

        const navSections = document.querySelectorAll('.nav-section');
        if (navSections[1]) {
            navSections[1].innerHTML = '<div class="nav-section-title">单字速览</div>'
                + sections.danzi.items.map(function (item) {
                    return '<div class="nav-item" onclick="jumpToChar(&quot;'
                        + escapeAttribute(item.word)
                        + '&quot;)"><span class="nav-emoji">'
                        + item.emoji
                        + '</span><span>'
                        + item.word
                        + '</span></div>';
                }).join('');
        }

        const logoArea = document.querySelector('.logo-area');
        if (logoArea && !logoArea.querySelector('.exercise-back-link')) {
            logoArea.insertAdjacentHTML('beforeend', '<a class="exercise-back-link" href="../构音训练.html">← 返回声母选择</a>');
        }

        render();
    }

    const synth = window.speechSynthesis;
    const idleLabel = '🔊 点击朗读';
    const playingLabel = '🔊 正在朗读...';
    const retryLabel = '🔊 请重试';
    let activeButton = null;
    let resetTimer = null;
    let chineseVoice = null;

    function findChineseVoice() {
        if (!synth) return null;
        const voices = synth.getVoices();
        return voices.find((voice) => /^zh[-_]CN$/i.test(voice.lang))
            || voices.find((voice) => /^zh/i.test(voice.lang))
            || null;
    }

    function loadVoice() {
        chineseVoice = findChineseVoice();
    }

    function getButton(cardEl) {
        return cardEl ? cardEl.querySelector('.play-btn') : null;
    }

    function resetButton(button, label) {
        if (!button) return;
        button.classList.remove('playing');
        button.textContent = label || idleLabel;
    }

    function finish(button, label) {
        if (resetTimer) {
            window.clearTimeout(resetTimer);
            resetTimer = null;
        }
        resetButton(button, label);
        if (activeButton === button) activeButton = null;
    }

    window.speak = function speak(text, cardEl) {
        const button = getButton(cardEl);
        const content = String(text || '').trim();

        if (!content) return;

        if (!synth || !window.SpeechSynthesisUtterance) {
            resetButton(button, '浏览器不支持朗读');
            window.alert('当前浏览器不支持语音朗读，请使用最新版 Chrome、Edge 或 Safari。');
            return;
        }

        if (activeButton && activeButton !== button) {
            resetButton(activeButton);
        }

        synth.cancel();
        if (synth.paused) synth.resume();

        const utterance = new SpeechSynthesisUtterance(content);
        utterance.lang = 'zh-CN';
        utterance.rate = 0.72;
        utterance.pitch = 1;
        utterance.volume = 1;

        if (!chineseVoice) loadVoice();
        if (chineseVoice) utterance.voice = chineseVoice;

        activeButton = button;
        if (button) {
            button.classList.add('playing');
            button.textContent = playingLabel;
        }

        utterance.onend = function () {
            finish(button);
        };

        utterance.onerror = function (event) {
            if (event.error === 'canceled' || event.error === 'interrupted') {
                finish(button);
                return;
            }
            finish(button, retryLabel);
            resetTimer = window.setTimeout(function () {
                resetButton(button);
            }, 1800);
        };

        synth.speak(utterance);

        // Some mobile browsers pause speech synthesis after the first utterance.
        window.setTimeout(function () {
            if (synth.paused) synth.resume();
        }, 120);
    };

    if (synth) {
        loadVoice();
        if (typeof synth.addEventListener === 'function') {
            synth.addEventListener('voiceschanged', loadVoice);
        } else {
            synth.onvoiceschanged = loadVoice;
        }
    }

    applyCuratedContent();
